"""Rebuild reference links and SOURCES.md for docs/deep_dive.

Usage: python3 scripts/build_deep_dive_refs.py
Fails loudly if a doc cites an ID that is not in the registry.
"""
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).parent))
from deep_dive_sources import ACCESSED, SOURCES  # noqa: E402

ROOT = pathlib.Path(__file__).resolve().parent.parent
DD = ROOT / "docs" / "deep_dive"
MARK = "<!-- reference links: generated by scripts/build_deep_dive_refs.py -->"
REG = {s[0]: s for s in SOURCES}
assert len(REG) == len(SOURCES), "duplicate source id"

used_by = {}
missing = []
for md in sorted(DD.glob("*.md")):
    if md.name == "SOURCES.md":
        continue
    text = md.read_text()
    body = text.split(MARK)[0].rstrip() + "\n"
    ids = sorted(set(re.findall(r"\[(S\d{3})\]", body)))
    for i in ids:
        if i not in REG:
            missing.append((md.name, i))
        used_by.setdefault(i, []).append(md.name)
    defs = "\n".join(f"[{i}]: {REG[i][4]}" for i in ids if i in REG)
    md.write_text(body + "\n" + MARK + "\n" + defs + "\n")

if missing:
    sys.exit(f"unknown source ids: {missing}")

lines = [
    "# Deep dive sources",
    "",
    f"Bibliography for `docs/deep_dive/`. Every link below was accessed on **{ACCESSED}**. "
    "The published date is the date shown by the publisher where we could see one (n.d. means none shown). "
    "IDs match the `[S001]` style citations in each deep dive file.",
    "",
    "Press articles that quote NIBSS, CBN or company filings are labelled with the underlying data owner in brackets. "
    "Where a primary document was reachable we cite it directly.",
    "",
    "| ID | Publisher | Title | Published | Cited in | Link |",
    "|---|---|---|---|---|---|",
]
for sid, pub, title, date, url in SOURCES:
    cited = ", ".join(sorted(set(used_by.get(sid, [])))) or "not cited yet"
    lines.append(f"| {sid} | {pub} | {title} | {date} | {cited} | [link]({url}) |")
(DD / "SOURCES.md").write_text("\n".join(lines) + "\n")
print(f"ok: {len(used_by)} of {len(SOURCES)} sources cited")
